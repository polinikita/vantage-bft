impl fmt::Display for ConsensusSignatureScheme {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(self.name())
    }
}

impl FromStr for ConsensusSignatureScheme {
    type Err = String;
    fn from_str(value: &str) -> Result<Self, Self::Err> {
        Self::ALL
            .iter()
            .copied()
            .find(|s| s.name() == value)
            .ok_or_else(|| {
                let names: Vec<_> = Self::ALL.iter().map(|s| s.name()).collect();
                format!(
                    "unknown consensus signature scheme '{value}'; expected one of: {}",
                    names.join(", ")
                )
            })
    }
}

/// `true` for the slow-signing SLH-DSA `…s` parameter sets. They are exposed
/// for completeness but sign at ~80–150 ms, far too slow for the per-vote
/// consensus path; callers may warn.
pub fn is_slow_signing(scheme: ConsensusSignatureScheme) -> bool {
    matches!(
        scheme,
        ConsensusSignatureScheme::SlhDsaSha2_128s
            | ConsensusSignatureScheme::SlhDsaSha2_192s
            | ConsensusSignatureScheme::SlhDsaSha2_256s
    )
}

// ---------------------------------------------------------------------------
// ConsensusSignature — the proof carried by ordering messages
// ---------------------------------------------------------------------------

/// A signature on the consensus/ordering path. `Ed25519` wraps the existing
/// 64-byte identity-key signature (preserving dalek batch verification);
/// `PostQuantum` carries the scheme-encoded bytes, validated on verify against
/// the author's [`ConsensusPublicKey`].
#[derive(Clone)]
pub enum ConsensusSignature {
    Ed25519(Signature),
    PostQuantum(Box<[u8]>),
}

impl PartialEq for ConsensusSignature {
    fn eq(&self, other: &Self) -> bool {
        match (self, other) {
            (Self::Ed25519(a), Self::Ed25519(b)) => a.to_bytes() == b.to_bytes(),
            (Self::PostQuantum(a), Self::PostQuantum(b)) => a == b,
            _ => false,
        }
    }
}
impl Eq for ConsensusSignature {}

impl Default for ConsensusSignature {
    fn default() -> Self {
        Self::Ed25519(Signature::default())
    }
}

impl fmt::Debug for ConsensusSignature {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Ed25519(_) => write!(f, "ed25519-sig"),
            Self::PostQuantum(bytes) => {
                write!(f, "pq-sig({})", hex::encode(&bytes[..bytes.len().min(4)]))
            }
        }
    }
}

impl ConsensusSignature {
    /// Sign `digest` with this node's consensus key material. The Ed25519
    /// identity secret is always available; `pq_secret` must be present for a
    /// post-quantum scheme.
    pub fn sign(
        digest: &Digest,
        identity_secret: &SecretKey,
        pq_secret: Option<&ConsensusSecretKey>,
    ) -> Self {
        match pq_secret {
            None => Self::Ed25519(Signature::new(digest, identity_secret)),
            Some(secret) => Self::PostQuantum(secret.sign_pq(&digest.0).into_boxed_slice()),
        }
    }

    /// Verify against `author` for `scheme`. Ed25519 uses the identity public
    /// key; post-quantum uses `pq_public` (the author's committee entry).
    pub fn verify(
        &self,
        digest: &Digest,
        author: &PublicKey,
        scheme: ConsensusSignatureScheme,
        pq_public: Option<&ConsensusPublicKey>,
    ) -> Result<(), ConsensusVerifyError> {
        match (scheme, self) {
            (ConsensusSignatureScheme::Ed25519, Self::Ed25519(sig)) => sig
                .verify(digest, author)
                .map_err(ConsensusVerifyError::Ed25519),
            (scheme, Self::PostQuantum(bytes)) if scheme.is_post_quantum() => {
                let key = pq_public.ok_or(ConsensusVerifyError::MissingKey)?;
                if key.scheme() != scheme {
                    return Err(ConsensusVerifyError::SchemeMismatch);
                }
                if key.verify_pq(&digest.0, bytes) {
                    Ok(())
                } else {
                    Err(ConsensusVerifyError::Invalid)
                }
            }
            _ => Err(ConsensusVerifyError::SchemeMismatch),
        }
    }

    /// The Ed25519 inner signature, if this is an Ed25519 proof. Used by the
    /// dalek batch-verification fast path.
    pub fn as_ed25519(&self) -> Option<&Signature> {
        match self {
            Self::Ed25519(sig) => Some(sig),
            Self::PostQuantum(_) => None,
        }
    }

    /// Canonical `tag || payload` encoding, identical to the wire encoding.
    /// Used wherever a digest must bind the exact signature bytes.
    pub fn to_canonical_bytes(&self) -> Vec<u8> {
        let mut bytes = Vec::new();
        match self {
            Self::Ed25519(sig) => {
                bytes.push(0u8);
                bytes.extend_from_slice(&sig.to_bytes());
            }
            Self::PostQuantum(payload) => {
                bytes.push(1u8);
                bytes.extend_from_slice(payload);
            }
        }
        bytes
    }
}

/// Verify a quorum of consensus signatures over a single `digest`. Ed25519
/// committees use dalek batch verification; post-quantum committees verify each
/// signature independently (no cross-key batching exists for ML-DSA/SLH-DSA).
pub fn verify_quorum<'a, I, F>(
    digest: &Digest,
    scheme: ConsensusSignatureScheme,
    votes: I,
    pq_public: F,
) -> Result<(), ConsensusVerifyError>
where
    I: IntoIterator<Item = &'a (PublicKey, ConsensusSignature)>,
    F: Fn(&PublicKey) -> Option<&'a ConsensusPublicKey>,
{
    if scheme.is_post_quantum() {
        for (author, sig) in votes {
            sig.verify(digest, author, scheme, pq_public(author))?;
        }
        return Ok(());
    }
    let mut ed = Vec::new();
    for (author, sig) in votes {
        match sig.as_ed25519() {
            Some(inner) => ed.push((*author, inner.clone())),
            None => return Err(ConsensusVerifyError::SchemeMismatch),
        }
    }
    Signature::verify_batch(digest, &ed).map_err(ConsensusVerifyError::Ed25519)
}

/// Like [`verify_quorum`] but each vote authenticates its own `digests[i]`.
pub fn verify_quorum_multi<'a, I, F>(
    digests: &[Digest],
    scheme: ConsensusSignatureScheme,
    votes: I,
    pq_public: F,
) -> Result<(), ConsensusVerifyError>
where
    I: IntoIterator<Item = &'a (PublicKey, ConsensusSignature)>,
    F: Fn(&PublicKey) -> Option<&'a ConsensusPublicKey>,
{
    if scheme.is_post_quantum() {
        for (i, (author, sig)) in votes.into_iter().enumerate() {
            sig.verify(&digests[i], author, scheme, pq_public(author))?;
        }
        return Ok(());
    }
    let mut ed = Vec::new();
    for (author, sig) in votes {
        match sig.as_ed25519() {
            Some(inner) => ed.push((*author, inner.clone())),
            None => return Err(ConsensusVerifyError::SchemeMismatch),
        }
    }
    Signature::verify_batch_multi(digests, &ed).map_err(ConsensusVerifyError::Ed25519)
}

// ---------------------------------------------------------------------------
// Key file encodings: `"<scheme>:<base64>"` strings, matching the committee
// and keypair JSON files' human-readable style.
// ---------------------------------------------------------------------------

fn serialize_scheme_key<S: Serializer>(
    scheme: ConsensusSignatureScheme,
    bytes: &[u8],
    serializer: S,
) -> Result<S::Ok, S::Error> {
    serializer.serialize_str(&format!("{scheme}:{}", BASE64_STANDARD.encode(bytes)))
}

fn parse_scheme_key<E: de::Error>(value: &str) -> Result<(ConsensusSignatureScheme, Vec<u8>), E> {
    let (scheme, payload) = value
        .split_once(':')
        .ok_or_else(|| E::custom("expected '<scheme>:<base64>'"))?;
    let scheme = ConsensusSignatureScheme::from_str(scheme).map_err(E::custom)?;
    let bytes = BASE64_STANDARD
        .decode(payload)
        .map_err(|e| E::custom(format!("invalid base64 key encoding: {e}")))?;
    Ok((scheme, bytes))
}

impl Serialize for ConsensusPublicKey {
    fn serialize<S: Serializer>(&self, serializer: S) -> Result<S::Ok, S::Error> {
        serialize_scheme_key(self.scheme(), &self.to_bytes(), serializer)
    }
}

impl<'de> Deserialize<'de> for ConsensusPublicKey {
    fn deserialize<D: Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {
        let value = String::deserialize(deserializer)?;
        let (scheme, bytes) = parse_scheme_key(&value)?;
        Self::from_bytes(scheme, &bytes).map_err(de::Error::custom)
    }
}

impl Serialize for ConsensusSecretKey {
    fn serialize<S: Serializer>(&self, serializer: S) -> Result<S::Ok, S::Error> {
        serialize_scheme_key(self.scheme(), &self.to_bytes(), serializer)
    }
}

impl<'de> Deserialize<'de> for ConsensusSecretKey {
    fn deserialize<D: Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {
        let value = String::deserialize(deserializer)?;
        let (scheme, bytes) = parse_scheme_key(&value)?;
        Self::from_bytes(scheme, &bytes).map_err(de::Error::custom)
    }
}

#[derive(Debug)]
pub enum ConsensusVerifyError {
    Ed25519(CryptoError),
    /// The carried proof's scheme does not match the committee scheme.
    SchemeMismatch,
    /// A post-quantum public key for the author is not in the committee.
    MissingKey,
    /// The post-quantum signature failed verification.
    Invalid,
}

impl fmt::Display for ConsensusVerifyError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Ed25519(e) => write!(f, "ed25519 verification failed: {e}"),
            Self::SchemeMismatch => write!(f, "consensus signature scheme mismatch"),
            Self::MissingKey => write!(f, "missing post-quantum consensus key for author"),
            Self::Invalid => write!(f, "post-quantum consensus signature is invalid"),
        }
    }
}
impl std::error::Error for ConsensusVerifyError {}

// ---------------------------------------------------------------------------
// Wire encoding: `scheme tag (u8) || payload`. Ed25519 tag = 0.
// ---------------------------------------------------------------------------

impl Serialize for ConsensusSignature {
    fn serialize<S: Serializer>(&self, serializer: S) -> Result<S::Ok, S::Error> {
        let mut bytes = Vec::new();
        match self {
            Self::Ed25519(sig) => {
                bytes.push(0u8);
                bytes.extend_from_slice(&sig.to_bytes());
            }
            Self::PostQuantum(payload) => {
                bytes.push(1u8);
                bytes.extend_from_slice(payload);
            }
        }
        serializer.serialize_bytes(&bytes)
    }
}

impl<'de> Deserialize<'de> for ConsensusSignature {
    fn deserialize<D: Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {
        struct V;
        impl<'de> de::Visitor<'de> for V {
            type Value = ConsensusSignature;
            fn expecting(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
                f.write_str("a tagged consensus signature")
            }
            fn visit_bytes<E: de::Error>(self, v: &[u8]) -> Result<Self::Value, E> {
                let (&tag, payload) = v
                    .split_first()
                    .ok_or_else(|| E::custom("empty signature"))?;
                match tag {
                    0 => {
                        let bytes: [u8; 64] = payload
                            .try_into()
                            .map_err(|_| E::custom("invalid ed25519 signature length"))?;
                        Ok(ConsensusSignature::Ed25519(Signature::from_bytes(&bytes)))
                    }
                    1 => Ok(ConsensusSignature::PostQuantum(payload.into())),
                    other => Err(E::custom(format!(
                        "unknown consensus signature tag {other}"
                    ))),
                }
            }
            fn visit_byte_buf<E: de::Error>(self, v: Vec<u8>) -> Result<Self::Value, E> {
                self.visit_bytes(&v)
            }
            fn visit_seq<A: de::SeqAccess<'de>>(self, mut seq: A) -> Result<Self::Value, A::Error> {
                let mut bytes = Vec::new();
                while let Some(b) = seq.next_element::<u8>()? {
                    bytes.push(b);
                }
                self.visit_bytes(&bytes)
            }
        }
        deserializer.deserialize_bytes(V)
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::generate_production_keypair;

    fn digest(byte: u8) -> Digest {
        Digest([byte; 32])
    }

    #[test]
    fn scheme_names_round_trip() {
        for &scheme in ConsensusSignatureScheme::ALL {
            assert_eq!(
                scheme.name().parse::<ConsensusSignatureScheme>().unwrap(),
                scheme
            );
            let json = serde_json::to_string(&scheme).unwrap();
            assert_eq!(json.trim_matches('"'), scheme.name());
            assert_eq!(
                serde_json::from_str::<ConsensusSignatureScheme>(&json).unwrap(),
                scheme
            );
        }
        assert!("rsa".parse::<ConsensusSignatureScheme>().is_err());
        assert_eq!(
            ConsensusSignatureScheme::default(),
            ConsensusSignatureScheme::Ed25519
        );
    }

    #[test]
    fn ed25519_sign_verify_and_batch() {
        let (name, secret) = generate_production_keypair();
        let d = digest(1);
        let sig = ConsensusSignature::sign(&d, &secret, None);
        assert!(sig
            .verify(&d, &name, ConsensusSignatureScheme::Ed25519, None)
            .is_ok());
        assert!(sig
            .verify(&digest(2), &name, ConsensusSignatureScheme::Ed25519, None)
            .is_err());

        let votes = vec![(name, sig.clone())];
        assert!(verify_quorum(&d, ConsensusSignatureScheme::Ed25519, &votes, |_| None).is_ok());
    }

    #[test]
    fn post_quantum_sign_verify_reject_and_quorum() {
        for &scheme in ConsensusSignatureScheme::ALL {
            if !scheme.is_post_quantum() {
                continue;
            }
            // Two authorities with distinct identity + PQ keys.
            let (name0, id0) = generate_production_keypair();
            let (name1, id1) = generate_production_keypair();
            let sk0 = ConsensusSecretKey::from_seed(scheme, &benchmark_seed(scheme, 0)).unwrap();
            let sk1 = ConsensusSecretKey::from_seed(scheme, &benchmark_seed(scheme, 1)).unwrap();
            let pk0 = sk0.public_key();
            let pk1 = sk1.public_key();
            assert_eq!(pk0.scheme(), scheme);
            assert_ne!(pk0, pk1);

            let d = digest(7);
            let s0 = ConsensusSignature::sign(&d, &id0, Some(&sk0));
            let s1 = ConsensusSignature::sign(&d, &id1, Some(&sk1));
            assert!(
                s0.verify(&d, &name0, scheme, Some(&pk0)).is_ok(),
                "{scheme}"
            );
            // wrong digest, wrong key, missing key, scheme mismatch all rejected
            assert!(s0.verify(&digest(8), &name0, scheme, Some(&pk0)).is_err());
            assert!(s0.verify(&d, &name0, scheme, Some(&pk1)).is_err());
            assert!(s0.verify(&d, &name0, scheme, None).is_err());
            assert!(s0
                .verify(&d, &name0, ConsensusSignatureScheme::Ed25519, None)
                .is_err());

            // Deterministic signing and size.
            assert_eq!(
                match &s0 {
                    ConsensusSignature::PostQuantum(b) => b.len(),
                    _ => 0,
                },
                scheme.signature_size(),
                "{scheme}"
            );

            // Quorum over one digest, keyed by author.
            let keys = [(name0, pk0.clone()), (name1, pk1.clone())];
            let lookup = |a: &PublicKey| keys.iter().find(|(n, _)| n == a).map(|(_, k)| k);
            let votes = vec![(name0, s0), (name1, s1)];
            assert!(
                verify_quorum(&d, scheme, &votes, lookup).is_ok(),
                "{scheme}"
            );

            // serde round-trip of a PQ signature.
            let enc = bincode::serialize(&votes[0].1).unwrap();
            let dec: ConsensusSignature = bincode::deserialize(&enc).unwrap();
            assert_eq!(dec, votes[0].1);
        }
    }

    #[test]
    fn key_encodings_round_trip() {
        for &scheme in ConsensusSignatureScheme::ALL {
            let Some(sk) = ConsensusSecretKey::from_seed(scheme, &benchmark_seed(scheme, 3)) else {
                continue;
            };
            let pk = sk.public_key();
            assert_eq!(pk.to_bytes().len(), scheme.public_key_size());
            let sk2 = ConsensusSecretKey::from_bytes(scheme, &sk.to_bytes()).unwrap();
            assert_eq!(sk2.public_key(), pk);
            let pk2 = ConsensusPublicKey::from_bytes(scheme, &pk.to_bytes()).unwrap();
            assert_eq!(pk2, pk);
        }
    }
}
