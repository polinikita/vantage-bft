/// Generate a fresh consensus keypair for `scheme` from OS randomness.
/// Returns `None` for Ed25519, which reuses the node's identity key.
pub fn generate_consensus_keypair(
    scheme: ConsensusSignatureScheme,
) -> Option<(ConsensusPublicKey, ConsensusSecretKey)> {
    use rand::RngCore as _;
    let mut seed = [0u8; 32];
    rand::rngs::OsRng.fill_bytes(&mut seed);
    let secret = ConsensusSecretKey::from_seed(scheme, &seed)?;
    Some((secret.public_key(), secret))
}

/// Deterministic per-authority seed for benchmark and test key material,
/// domain-separated by scheme.
pub fn benchmark_seed(scheme: ConsensusSignatureScheme, authority: u64) -> [u8; 32] {
    let mut hasher = blake3::Hasher::new_derive_key("vantage consensus authentication seed");
    hasher.update(scheme.name().as_bytes());
    hasher.update(&authority.to_le_bytes());
    hasher.finalize().into()
}

/// Derive a signing key for `scheme` from a 32-byte seed. Ed25519 returns
/// `None` (it reuses the node's identity key).
pub fn consensus_secret_from_seed(
    scheme: ConsensusSignatureScheme,
    seed: &[u8; 32],
) -> Option<ConsensusSecretKey> {
    ConsensusSecretKey::from_seed(scheme, seed)
}

fn expand_seed(scheme_name: &str, seed: &[u8; 32], output: &mut [u8]) {
    let mut hasher = blake3::Hasher::new_derive_key("vantage consensus key expansion");
    hasher.update(scheme_name.as_bytes());
    hasher.update(seed);
    hasher.finalize_xof().fill(output);
}

// ---------------------------------------------------------------------------
// Scheme registry — the single place listing every post-quantum scheme.
// ---------------------------------------------------------------------------

macro_rules! consensus_signature_schemes {
    ($( $variant:ident($scheme:ty, $name:literal) ),+ $(,)?) => {
        /// Signature scheme authenticating the Autobahn consensus/ordering path
        /// (committee-wide; committee field `consensus_signature_scheme`).
        #[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Hash, Serialize, Deserialize)]
        pub enum ConsensusSignatureScheme {
            #[default]
            #[serde(rename = "ed25519")]
            Ed25519,
            $( #[serde(rename = $name)] $variant, )+
        }

        impl ConsensusSignatureScheme {
            pub const ALL: &'static [Self] = &[Self::Ed25519, $( Self::$variant, )+];

            pub fn name(self) -> &'static str {
                match self {
                    Self::Ed25519 => "ed25519",
                    $( Self::$variant => <$scheme>::NAME, )+
                }
            }

            pub fn is_post_quantum(self) -> bool {
                !matches!(self, Self::Ed25519)
            }

            pub fn public_key_size(self) -> usize {
                match self {
                    Self::Ed25519 => 32,
                    $( Self::$variant => <$scheme>::PUBLIC_KEY_SIZE, )+
                }
            }

            pub fn signature_size(self) -> usize {
                match self {
                    Self::Ed25519 => 64,
                    $( Self::$variant => <$scheme>::SIGNATURE_SIZE, )+
                }
            }
        }

        /// Post-quantum public key of one authority for the selected scheme.
        #[derive(Clone, Debug, PartialEq, Eq)]
        pub enum ConsensusPublicKey {
            $( $variant(PqPublicKey<$scheme>), )+
        }

        impl ConsensusPublicKey {
            pub fn scheme(&self) -> ConsensusSignatureScheme {
                match self { $( Self::$variant(_) => ConsensusSignatureScheme::$variant, )+ }
            }
            pub fn from_bytes(scheme: ConsensusSignatureScheme, bytes: &[u8]) -> Result<Self, String> {
                match scheme {
                    ConsensusSignatureScheme::Ed25519 =>
                        Err("ed25519 uses the authority identity key".into()),
                    $( ConsensusSignatureScheme::$variant =>
                        PqPublicKey::<$scheme>::from_bytes(bytes).map(Self::$variant), )+
                }
            }
            pub fn to_bytes(&self) -> Vec<u8> {
                match self { $( Self::$variant(k) => k.to_bytes(), )+ }
            }
            fn verify_pq(&self, message: &[u8; 32], signature: &[u8]) -> bool {
                match self { $( Self::$variant(k) => k.verify(message, signature), )+ }
            }
        }

        /// Post-quantum signing key of this node for the selected scheme.
        #[derive(Clone, Debug)]
        pub enum ConsensusSecretKey {
            $( $variant(PqSigner<$scheme>), )+
        }

        impl ConsensusSecretKey {
            pub fn from_seed(scheme: ConsensusSignatureScheme, seed: &[u8; 32]) -> Option<Self> {
                match scheme {
                    ConsensusSignatureScheme::Ed25519 => None,
                    $( ConsensusSignatureScheme::$variant =>
                        Some(Self::$variant(PqSigner::<$scheme>::from_seed(seed))), )+
                }
            }
            pub fn from_bytes(scheme: ConsensusSignatureScheme, bytes: &[u8]) -> Result<Self, String> {
                match scheme {
                    ConsensusSignatureScheme::Ed25519 =>
                        Err("ed25519 uses the authority identity key".into()),
                    $( ConsensusSignatureScheme::$variant =>
                        PqSigner::<$scheme>::from_bytes(bytes).map(Self::$variant), )+
                }
            }
            pub fn scheme(&self) -> ConsensusSignatureScheme {
                match self { $( Self::$variant(_) => ConsensusSignatureScheme::$variant, )+ }
            }
            pub fn to_bytes(&self) -> Vec<u8> {
                match self { $( Self::$variant(k) => k.to_bytes(), )+ }
            }
            pub fn public_key(&self) -> ConsensusPublicKey {
                match self { $( Self::$variant(k) => ConsensusPublicKey::$variant(k.public_key()), )+ }
            }
            fn sign_pq(&self, message: &[u8; 32]) -> Vec<u8> {
                match self { $( Self::$variant(k) => k.sign(message), )+ }
            }
        }
    };
}

