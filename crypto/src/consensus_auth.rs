macro_rules! impl_ml_dsa_scheme {
    ($marker:ident, $params:ty, $name:literal, pk = $pk:literal, sig = $sig:literal) => {
        #[derive(Clone, Copy, Debug, PartialEq, Eq)]
        pub struct $marker;

        impl PqSignatureScheme for $marker {
            const NAME: &'static str = $name;
            const PUBLIC_KEY_SIZE: usize = $pk;
            /// ML-DSA private keys are stored as their 32-byte seed.
            const SECRET_KEY_SIZE: usize = 32;
            const SIGNATURE_SIZE: usize = $sig;

            type SigningKey = ml_dsa::SigningKey<$params>;
            type VerifyingKey = ml_dsa::VerifyingKey<$params>;

            fn keygen_from_seed(seed: &[u8; 32]) -> Self::SigningKey {
                ml_dsa::SigningKey::<$params>::from_seed(&ml_dsa::Seed::from(*seed))
            }
            fn signing_key_to_bytes(key: &Self::SigningKey) -> Vec<u8> {
                key.to_seed().to_vec()
            }
            fn signing_key_from_bytes(bytes: &[u8]) -> Option<Self::SigningKey> {
                let seed: [u8; 32] = bytes.try_into().ok()?;
                Some(Self::keygen_from_seed(&seed))
            }
            fn verifying_key(key: &Self::SigningKey) -> Self::VerifyingKey {
                ml_dsa::Keypair::verifying_key(key)
            }
            fn verifying_key_to_bytes(key: &Self::VerifyingKey) -> Vec<u8> {
                key.encode().to_vec()
            }
            fn verifying_key_from_bytes(bytes: &[u8]) -> Option<Self::VerifyingKey> {
                let encoded = ml_dsa::EncodedVerifyingKey::<$params>::try_from(bytes).ok()?;
                Some(ml_dsa::VerifyingKey::<$params>::decode(&encoded))
            }
            fn sign(key: &Self::SigningKey, message: &[u8]) -> Vec<u8> {
                let signature: ml_dsa::Signature<$params> = ml_dsa::Signer::sign(key, message);
                signature.encode().to_vec()
            }
            fn verify(key: &Self::VerifyingKey, message: &[u8], signature: &[u8]) -> bool {
                let Ok(signature) = ml_dsa::Signature::<$params>::try_from(signature) else {
                    return false;
                };
                ml_dsa::Verifier::verify(key, message, &signature).is_ok()
            }
        }
    };
}

