//! Pluggable signature schemes for the Autobahn consensus/ordering path.
//!
//! The DAG/data path (headers, car dissemination) keeps using the Ed25519
//! identity key ([`crate::Signature`]). The *ordering* messages — car votes,
//! quorum certificates, PoA certificates, prepare/confirm/commit consensus
//! messages, and timeouts — instead carry a [`ConsensusSignature`], whose
//! scheme is fixed committee-wide by [`ConsensusSignatureScheme`].
//!
//! An authority's identity remains its Ed25519 public key. When a post-quantum
//! scheme is selected, each authority additionally holds a
//! [`ConsensusPublicKey`] (published in the committee) and the matching
//! [`ConsensusSecretKey`]. Ed25519 is the default and requires no extra keys;
//! its `ConsensusSignature` wraps the existing 64-byte [`crate::Signature`], so
//! the fast dalek batch-verification path is preserved for quorum certificates.
//!
//! Post-quantum schemes are implemented behind [`PqSignatureScheme`]; each is a
//! zero-sized marker type and the dispatch enums are generated by the
//! `consensus_signature_schemes!` macro. Adding a scheme is one macro line.

use std::{fmt, str::FromStr};

use base64::prelude::{Engine as _, BASE64_STANDARD};
use serde::{de, Deserialize, Deserializer, Serialize, Serializer};

use crate::{CryptoError, Digest, PublicKey, SecretKey, Signature};

